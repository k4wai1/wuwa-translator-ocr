#!/usr/bin/env python3
"""Train a lightweight YOLOv8n character detector on the synthetic Solaris-3 dataset.

The dataset is generated by scripts/generate_dataset.py. Training runs on CPU with
conservative settings for low-RAM machines; adjust --batch / --imgsz if you have
more hardware.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", default=str(ROOT / "training" / "dataset" / "data.yaml"))
    ap.add_argument("--model", default="yolov8n.pt")
    ap.add_argument("--epochs", type=int, default=45)
    ap.add_argument("--imgsz", type=int, default=416)
    ap.add_argument("--batch", type=int, default=8)
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--patience", type=int, default=18)
    ap.add_argument("--name", default="solaris_yolov8n_416")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--fraction", type=float, default=1.0, help="Use a subset (0-1) for smoke tests")
    args = ap.parse_args()

    from ultralytics import YOLO

    project = ROOT / "training" / "runs"
    model = YOLO(args.model)
    model.train(
        data=args.data,
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        workers=args.workers,
        device="cpu",
        project=str(project),
        name=args.name,
        exist_ok=True,
        pretrained=True,
        optimizer="auto",
        patience=args.patience,
        seed=args.seed,
        deterministic=False,
        cache=False,
        plots=True,
        val=True,
        save_period=10,
        fraction=args.fraction,
        # --- augmentation: geometry is already applied by the dataset generator ---
        degrees=0.0,
        translate=0.05,
        scale=0.25,
        shear=0.0,
        perspective=0.0,
        fliplr=0.0,  # NEVER flip: it would turn characters into different glyphs
        flipud=0.0,
        mosaic=0.30,
        close_mosaic=8,
        mixup=0.0,
        copy_paste=0.0,
        erasing=0.0,
        hsv_h=0.015,
        hsv_s=0.35,
        hsv_v=0.35,
        # --- optimisation for CPU ---
        cos_lr=True,
        lr0=0.01,
        lrf=0.01,
        warmup_epochs=3.0,
        weight_decay=0.0005,
        amp=False,
        verbose=True,
    )

    best = project / args.name / "weights" / "best.pt"
    metrics_path = project / args.name / "metrics.json"
    payload = {"best": str(best), "args": vars(args)}
    try:
        metrics = model.val(
            data=args.data,
            imgsz=args.imgsz,
            batch=args.batch,
            workers=args.workers,
            device="cpu",
            plots=True,
            project=str(project),
            name=f"{args.name}_val",
            exist_ok=True,
        )
        payload["metrics"] = {k: float(v) for k, v in metrics.results_dict.items()}
        payload["per_class"] = {
            str(k): float(v) for k, v in zip(metrics.box.ap_class_index.tolist(), metrics.box.ap50)
        }
    except Exception as exc:  # noqa: BLE001 - keep the training result even if val fails
        payload["metrics_error"] = repr(exc)
    metrics_path.write_text(json.dumps(payload, indent=2))
    print(json.dumps(payload, indent=2))
    print(f"[train] best weights: {best}")


if __name__ == "__main__":
    main()
